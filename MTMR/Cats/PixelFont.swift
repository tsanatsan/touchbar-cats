    /// The glyph's pixels around its center, in a 14 x 14 box; capitals use the small letter's shape.
    /// nil for characters the font doesn't have
    static func pixels(_ ch: String) -> [(Int, Int)]? {
        guard let g = glyphs[ch] ?? glyphs[ch.lowercased()] else { return nil }
        let rows = g.rows.split(separator: " ")
        let width = rows.first?.count ?? 0
        let left = (14 - width) / 2
        var result: [(Int, Int)] = []
        for (r, row) in rows.enumerated() {
            for (c, v) in row.enumerated() where v == "#" {
                result.append((left + c - 7, g.top + r + 1 - 7))
            }
        }
        return result
    }
